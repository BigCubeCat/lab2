static const FontGlyph *find_glyph(uint32_t codepoint) {
    for (size_t i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i) {
        if (glyphs[i].codepoint == codepoint)
            return &glyphs[i];
    }
    return NULL;
}

void font_draw_char(int x, int y, uint32_t codepoint) {
    const FontGlyph *glyph = find_glyph(codepoint);
    if (glyph == NULL)
        return;

    for (int row = 0; row < FONT_HEIGHT; ++row) {
        const uint8_t bits = glyph_bitmap[glyph->offset + row];
        for (int col = 0; col < glyph->width; ++col) {
            if (bits & (1u << col))
                oled_draw_pixel(x + col, y + row, 1);
        }
    }
}

static uint32_t utf8_next(const char **ptr) {
    const unsigned char *s = (const unsigned char *)*ptr;
    if (*s == 0)
        return 0;

    uint32_t cp;
    size_t n;

    if (s[0] < 0x80) {
        cp = s[0];
        n = 1;
    } else if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x1F) << 6) | (uint32_t)(s[1] & 0x3F);
        n = 2;
    } else if ((s[0] & 0xF0) == 0xE0 &&
               (s[1] & 0xC0) == 0x80 &&
               (s[2] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x0F) << 12) |
             ((uint32_t)(s[1] & 0x3F) << 6) |
             (uint32_t)(s[2] & 0x3F);
        n = 3;
    } else if ((s[0] & 0xF8) == 0xF0 &&
               (s[1] & 0xC0) == 0x80 &&
               (s[2] & 0xC0) == 0x80 &&
               (s[3] & 0xC0) == 0x80) {
        cp = ((uint32_t)(s[0] & 0x07) << 18) |
             ((uint32_t)(s[1] & 0x3F) << 12) |
             ((uint32_t)(s[2] & 0x3F) << 6) |
             (uint32_t)(s[3] & 0x3F);
        n = 4;
    } else {
        ++(*ptr);
        return 0xFFFFFFFFu;
    }

    *ptr += n;
    return cp;
}

void font_draw_text(int x, int y, const char *text) {
    if (text == NULL)
        return;

    int cursor_x = x;
    const char *p = text;

    while (*p != '\0') {
        const char *before = p;
        const uint32_t cp = utf8_next(&p);
        if (cp == 0xFFFFFFFFu) {
            continue;
        }

        const FontGlyph *glyph = find_glyph(cp);
        if (glyph == NULL) {
            cursor_x += 4;
            continue;
        }

        font_draw_char(cursor_x, y, cp);
        cursor_x += glyph->advance;
    }
}

int font_text_width(const char *text) {
    if (text == NULL)
        return 0;

    int width = 0;
    const char *p = text;

    while (*p != '\0') {
        const uint32_t cp = utf8_next(&p);
        if (cp == 0xFFFFFFFFu)
            continue;

        const FontGlyph *glyph = find_glyph(cp);
        if (glyph != NULL)
            width += glyph->advance;
    }

    return width;
}
